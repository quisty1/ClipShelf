import Foundation
import ClipShelfCore

@MainActor struct PayloadTests {
    func formatsArePartOfIdentity() {
        let plain = ClipPayload(text: "hello")
        let rich = ClipPayload(text: "hello", rtf: Data([1, 2]))
        expect(plain.fingerprint != rich.fingerprint)
        expect(plain.fingerprint == ClipPayload(text: "hello").fingerprint)
    }

    func classifiesOnlyCompleteWebURLs() {
        expect(ClipPayload(text: "https://apple.com/a").kind == .link)
        expect(ClipPayload(text: "visit https://apple.com").kind == .text)
        expect(ClipPayload(text: "example.com").kind == .text)
        expect(ClipPayload(png: Data([1])).kind == .image)
    }

    func transformationsPreserveSource() {
        let original = "  Привет\nМир  "
        expect(TextTransform.trim.apply(original) == "Привет\nМир")
        expect(TextTransform.uppercase.apply(original) == "  ПРИВЕТ\nМИР  ")
        expect(TextTransform.lowercase.apply(original) == "  привет\nмир  ")
        expect(original == "  Привет\nМир  ")
    }

    func policyDiscardsPausedExcludedAndSensitiveCopies() {
        expect(!CapturePolicy.allows(paused: true, source: "org.editor", excluded: [], types: []))
        expect(!CapturePolicy.allows(paused: false, source: "org.secret", excluded: ["org.secret"], types: []))
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "app.clipshelf.own"] {
            expect(!CapturePolicy.allows(paused: false, source: nil, excluded: [], types: [marker]))
        }
        expect(CapturePolicy.allows(paused: false, source: "org.editor", excluded: [], types: ["public.utf8-plain-text"]))
    }

    func countsPreventDuplicateOwnAndPausedEvents() {
        var cursor = CaptureCursor(initialCount: 4)
        expect(!cursor.consume(4))
        expect(cursor.consume(5))
        expect(!cursor.consume(5))
        cursor.ignoreThrough(8)
        expect(!cursor.consume(8))
        expect(cursor.consume(9))
    }

    func sourceTransitionsDiscardAmbiguousCopies() {
        var cursor = CaptureCursor(initialCount: 10, sourceID: "org.secret")
        cursor.sourceChanged("org.editor", currentCount: 11)
        expect(!cursor.consume(11, sourceID: "org.editor"))
        expect(cursor.consume(12, sourceID: "org.editor"))
        // Also reject if a transition notification has not arrived yet.
        expect(!cursor.consume(13, sourceID: "org.other"))
        expect(cursor.consume(14, sourceID: "org.other"))
    }
}

@MainActor
struct RepositoryTests {
    func repository() throws -> (ClipRepository, URL) {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        return (try ClipRepository(directory: directory, inMemory: true), directory)
    }

    func duplicatesMoveToTopAndSearchIncludesTitle() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        let first = try repo.capture(ClipPayload(text: "Привет мир"), sourceName: "Редактор", sourceID: "org.editor", at: Date(timeIntervalSince1970: 10))
        _ = try repo.capture(ClipPayload(text: "Другая запись"), at: Date(timeIntervalSince1970: 20))
        let again = try repo.capture(ClipPayload(text: "Привет мир"), at: Date(timeIntervalSince1970: 30))
        expect(first.id == again.id)
        expect(repo.entries.count == 2)
        expect(repo.entries.first?.id == first.id)
        try repo.edit(first, title: "Ответ клиенту", text: "Привет мир", snippet: false)
        expect(repo.search("КЛИЕНТУ").map(\.id) == [first.id])
        expect(repo.search("привет").map(\.id) == [first.id])
    }

    func deletingCollectionKeepsEntries() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        let a = try repo.createCollection("Работа")
        let b = try repo.createCollection("Личное")
        let entry = try repo.capture(ClipPayload(text: "Hello"))
        try repo.toggleCollection(a.id, for: entry)
        try repo.toggleCollection(b.id, for: entry)
        try repo.deleteCollection(a)
        expect(repo.entries.count == 1)
        expect(entry.collectionIDs == [b.id])
        expect(repo.collections.map(\.id) == [b.id])
    }

    func retentionProtectsFavoritesSnippetsAndCollections() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        let old = Date(timeIntervalSince1970: 0)
        let favorite = try repo.capture(ClipPayload(text: "favorite"), at: old)
        try repo.toggleFavorite(favorite)
        let snippet = try repo.saveSnippet(title: "Ответ", text: "snippet")
        let collection = try repo.createCollection("Keep")
        let collected = try repo.capture(ClipPayload(text: "collection"), at: old)
        try repo.toggleCollection(collection.id, for: collected)
        _ = try repo.capture(ClipPayload(text: "expire"), at: old)
        let now = Date()
        _ = try repo.capture(ClipPayload(text: "prune"), at: now.addingTimeInterval(-3))
        let fresh = try repo.capture(ClipPayload(text: "fresh"), at: now)
        try repo.prune(limit: 1, days: 30, now: now)
        expect(Set(repo.entries.map(\.id)) == Set([favorite.id, snippet.id, collected.id, fresh.id]))
    }

    func imageDeletionCleansFileAndRoundTripsPayload() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        let bytes = Data([137, 80, 78, 71])
        let entry = try repo.capture(ClipPayload(png: bytes))
        let file = try require(repo.imageURL(for: entry))
        expect(FileManager.default.fileExists(atPath: file.path))
        expect(try repo.payload(for: entry).png == bytes)
        try repo.delete(entry)
        expect(!FileManager.default.fileExists(atPath: file.path))
    }

    func persistentStoreRestoresRichContentAndCollections() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        var entryID: UUID?
        do {
            let repo = try ClipRepository(directory: dir)
            let collection = try repo.createCollection("Работа")
            let entry = try repo.capture(ClipPayload(text: "Styled", rtf: Data([1]), html: Data([2])))
            try repo.toggleCollection(collection.id, for: entry)
            entryID = entry.id
        }
        let restored = try ClipRepository(directory: dir)
        expect(restored.entries.first?.id == entryID)
        expect(restored.entries.first?.rtf == Data([1]))
        expect(restored.entries.first?.html == Data([2]))
        expect(restored.entries.first?.collectionIDs == restored.collections.map(\.id))
    }

    func snippetsRemainIndependentAndEditsDoNotChangeHistory() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        let history = try repo.capture(ClipPayload(text: "Original", rtf: Data([1])))
        let snippet = try repo.saveSnippet(title: "Template", text: "Original")
        try repo.edit(snippet, title: "Changed", text: "Edited", snippet: true)
        expect(history.text == "Original")
        expect(history.rtf == Data([1]))
        expect(snippet.text == "Edited")
        expect(repo.entries.count == 2)
        expect(repo.search("Changed", kind: .text).map(\.id) == [snippet.id])
        try repo.clear()
        expect(repo.entries.map(\.id) == [snippet.id])
        try repo.clear(includeProtected: true)
        expect(repo.entries.isEmpty)
    }

    func thousandEntrySearchAndRetention() throws {
        let (repo, dir) = try repository()
        defer { try? FileManager.default.removeItem(at: dir) }
        for i in 0..<1003 {
            _ = try repo.capture(ClipPayload(text: "Document \(i) content for history search"), at: Date().addingTimeInterval(Double(i)))
        }
        try repo.prune(limit: 1000, days: 30)
        expect(repo.entries.count == 1000)
        expect(repo.entries.last?.text == "Document 3 content for history search")
        let start = Date()
        expect(repo.search("DOCUMENT 1002").count == 1)
        expect(repo.search("history").count == 1000)
        print("Search of 1000 entries: \(String(format: "%.3f", Date().timeIntervalSince(start))) s")
    }

    func clearingHistoryPreservesProtectedEntriesAndImagesAcrossRestart() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let repo = try ClipRepository(directory: dir)
        let normal = try repo.capture(ClipPayload(png: Data([1])))
        let normalImage = try require(repo.imageURL(for: normal))
        let favorite = try repo.capture(ClipPayload(png: Data([2])))
        try repo.toggleFavorite(favorite)
        let favoriteImage = try require(repo.imageURL(for: favorite))
        let collection = try repo.createCollection("Моя коллекция")
        let collected = try repo.capture(ClipPayload(png: Data([3])))
        try repo.toggleCollection(collection.id, for: collected)
        let collectedImage = try require(repo.imageURL(for: collected))
        let snippet = try repo.saveSnippet(title: "Шаблон", text: "Содержимое")
        _ = try repo.capture(ClipPayload(text: "ordinary"))
        try repo.clear(includeProtected: false)
        expect(!FileManager.default.fileExists(atPath: normalImage.path))
        expect(FileManager.default.fileExists(atPath: favoriteImage.path))
        expect(FileManager.default.fileExists(atPath: collectedImage.path))
        let restored = try ClipRepository(directory: dir)
        expect(Set(restored.entries.map(\.id)) == Set([favorite.id, collected.id, snippet.id]))
        expect(restored.collections.first?.name == "Моя коллекция")
        expect(try restored.payload(for: require(restored.entries.first { $0.id == favorite.id })).png == Data([2]))
        try restored.clear()
        expect(restored.entries.count == 3)
    }

    func failedClearKeepsEntriesAndImages() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let storage = ClearFailureStorage()
        let repo = try ClipRepository(directory: dir, storage: storage)
        let entry = try repo.capture(ClipPayload(png: Data([1, 2, 3])))
        let imageURL = try require(repo.imageURL(for: entry))
        storage.failSaves = true
        do { try repo.clear(); expect(false) } catch {}
        expect(repo.entries.map(\.id) == [entry.id])
        expect(FileManager.default.fileExists(atPath: imageURL.path))
        let restored = try ClipRepository(directory: dir, storage: storage)
        expect(restored.entries.map(\.id) == [entry.id])
        expect(try restored.payload(for: require(restored.entries.first)).png == Data([1, 2, 3]))
    }

    func firstSaveFailureLeavesNoGhostOrBrokenImageReference() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let storage = FailingStorage()
        let repo = try ClipRepository(directory: dir, storage: storage)
        do { _ = try repo.capture(ClipPayload(png: Data([1, 2]))); expect(false) } catch {}
        expect(repo.entries.isEmpty)
        expect(try FileManager.default.contentsOfDirectory(atPath: repo.imageDirectory.path).isEmpty)
        _ = try repo.capture(ClipPayload(text: "Recovered"))
        let restored = try ClipRepository(directory: dir, storage: storage)
        expect(restored.entries.count == 1)
        expect(restored.entries.first?.text == "Recovered")
        expect(restored.entries.first?.imageName == nil)
    }
}

@MainActor final class FailingStorage: SnapshotStorage {
    var data: Data?
    private var failNext = true
    func load() throws -> Data? { data }
    func save(_ snapshot: Data) throws {
        if failNext { failNext = false; throw CocoaError(.fileWriteUnknown) }
        data = snapshot
    }
}

@MainActor private final class ClearFailureStorage: SnapshotStorage {
    var data: Data?
    var failSaves = false
    func load() throws -> Data? { data }
    func save(_ snapshot: Data) throws {
        if failSaves { throw CocoaError(.fileWriteUnknown) }
        data = snapshot
    }
}
