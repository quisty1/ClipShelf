import Foundation
import CryptoKit
import Observation

public enum ClipKind: String, Codable, CaseIterable, Sendable {
    case text, link, image
    public var label: String { switch self { case .text: "Текст"; case .link: "Ссылки"; case .image: "Изображения" } }
    public var symbol: String { switch self { case .text: "text.alignleft"; case .link: "link"; case .image: "photo" } }
}

public struct ClipPayload: Sendable {
    public var text: String?
    public var rtf: Data?
    public var html: Data?
    public var png: Data?

    public init(text: String? = nil, rtf: Data? = nil, html: Data? = nil, png: Data? = nil) {
        self.text = text; self.rtf = rtf; self.html = html; self.png = png
    }

    public var kind: ClipKind {
        if png != nil { return .image }
        if let value = text?.trimmingCharacters(in: .whitespacesAndNewlines),
           !value.contains(where: \.isWhitespace), let url = URL(string: value),
           ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil { return .link }
        return .text
    }

    public var fingerprint: String {
        var hash = SHA256()
        for part in [text.map { Data($0.utf8) }, rtf, html, png] {
            // Presence plus byte length preserves boundaries and distinguishes nil from empty.
            hash.update(data: Data("\(part == nil ? -1 : part!.count):".utf8))
            if let part { hash.update(data: part) }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

@MainActor @Observable public final class ClipEntry {
    public var id: UUID
    public var fingerprint: String
    public var text: String?
    public var rtf: Data?
    public var html: Data?
    public var imageName: String?
    public var kindRaw: String
    public var title: String
    public var createdAt: Date
    public var lastCopiedAt: Date
    public var sourceName: String
    public var sourceID: String
    public var isFavorite: Bool
    public var isSnippet: Bool
    public var collectionIDs: [UUID]

    public init(payload: ClipPayload, imageName: String?, sourceName: String, sourceID: String, at: Date) {
        id = UUID(); fingerprint = payload.fingerprint
        text = payload.text; rtf = payload.rtf; html = payload.html; self.imageName = imageName
        kindRaw = payload.kind.rawValue; title = ""; createdAt = at; lastCopiedAt = at
        self.sourceName = sourceName; self.sourceID = sourceID
        isFavorite = false; isSnippet = false; collectionIDs = []
    }

    public var kind: ClipKind { ClipKind(rawValue: kindRaw) ?? .text }
    public var isProtected: Bool { isFavorite || isSnippet || !collectionIDs.isEmpty }
    public var displayTitle: String {
        if !title.isEmpty { return title }
        if kind == .image { return "Изображение" }
        let line = text?.split(whereSeparator: \.isNewline).first.map(String.init) ?? "Пустой текст"
        return String(line.prefix(160))
    }
}

@MainActor @Observable public final class ClipCollection {
    public var id: UUID
    public var name: String
    public var createdAt: Date
    public init(name: String) { id = UUID(); self.name = name; createdAt = Date() }
}

public enum TextTransform: String, CaseIterable, Sendable {
    case plain, trim, uppercase, lowercase
    public var label: String {
        switch self {
        case .plain: "Без форматирования"
        case .trim: "Убрать пробелы по краям"
        case .uppercase: "В ВЕРХНИЙ РЕГИСТР"
        case .lowercase: "в нижний регистр"
        }
    }
    public func apply(_ value: String) -> String {
        switch self {
        case .plain: value
        case .trim: value.trimmingCharacters(in: .whitespacesAndNewlines)
        case .uppercase: value.uppercased()
        case .lowercase: value.lowercased()
        }
    }
}

public enum CapturePolicy {
    public static let ownType = "app.clipshelf.own"
    public static let blockedTypes: Set<String> = [ownType, "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"]
    public static func allows(paused: Bool, source: String?, excluded: Set<String>, types: Set<String>) -> Bool {
        !paused && (source == nil || !excluded.contains(source!)) && types.isDisjoint(with: blockedTypes)
    }
}

public struct CaptureCursor: Sendable {
    private var count: Int
    private var sourceID: String?
    public init(initialCount: Int, sourceID: String? = nil) { count = initialCount; self.sourceID = sourceID }
    public mutating func sourceChanged(_ sourceID: String?, currentCount: Int) {
        self.sourceID = sourceID; count = currentCount
    }
    public mutating func consume(_ newCount: Int, sourceID: String?) -> Bool {
        guard self.sourceID == sourceID else { sourceChanged(sourceID, currentCount: newCount); return false }
        return consume(newCount)
    }
    public mutating func consume(_ newCount: Int) -> Bool {
        guard newCount != count else { return false }
        count = newCount
        return true
    }
    public mutating func ignoreThrough(_ newCount: Int) { count = newCount }
}

struct EntrySnapshot: Codable {
    var id: UUID; var fingerprint: String; var text: String?; var rtf: Data?; var html: Data?
    var imageName: String?; var kindRaw: String; var title: String; var createdAt: Date; var lastCopiedAt: Date
    var sourceName: String; var sourceID: String; var isFavorite: Bool; var isSnippet: Bool; var collectionIDs: [UUID]
    @MainActor init(_ e: ClipEntry) {
        id = e.id; fingerprint = e.fingerprint; text = e.text; rtf = e.rtf; html = e.html; imageName = e.imageName
        kindRaw = e.kindRaw; title = e.title; createdAt = e.createdAt; lastCopiedAt = e.lastCopiedAt
        sourceName = e.sourceName; sourceID = e.sourceID; isFavorite = e.isFavorite; isSnippet = e.isSnippet; collectionIDs = e.collectionIDs
    }
    @MainActor func materialize() -> ClipEntry {
        let e = ClipEntry(payload: ClipPayload(text: text, rtf: rtf, html: html), imageName: imageName, sourceName: sourceName, sourceID: sourceID, at: createdAt)
        e.id = id; e.fingerprint = fingerprint; e.kindRaw = kindRaw; e.title = title; e.lastCopiedAt = lastCopiedAt
        e.isFavorite = isFavorite; e.isSnippet = isSnippet; e.collectionIDs = collectionIDs
        return e
    }
}
struct CollectionSnapshot: Codable {
    var id: UUID; var name: String; var createdAt: Date
    @MainActor init(_ c: ClipCollection) { id = c.id; name = c.name; createdAt = c.createdAt }
    @MainActor func materialize() -> ClipCollection {
        let c = ClipCollection(name: name); c.id = id; c.createdAt = createdAt; return c
    }
}
